"""Reference descent times for the brachistochrone variants.

The ideal variant has a closed form: the optimal path is the cycloid
``x = R(theta - sin theta)``, ``y = R(1 - cos theta)``, traversed in
``t = theta sqrt(R / g)``. Requiring the curve to pass through the target
fixes ``theta_f`` through a transcendental equation in the aspect ratio,
and ``R`` follows from the depth.

The friction and drag variants have no comparably simple closed form, so
their references are high-accuracy numerical values regenerated by
``tools/generate_brachistochrone_references.py`` and stored here, rather
than a formula asserted without proof.
"""

from __future__ import annotations

import math

from scipy.optimize import brentq

from gemseo_tempo.problems.brachistochrone.model import GRAVITY
from gemseo_tempo.problems.brachistochrone.model import TARGET

STORED_REFERENCES = {
    ("friction", 2.0, 2.0, 9.81): 0.955676,
    ("drag", 2.0, 2.0, 9.81): 0.847311,
}
"""High-accuracy descent times, keyed by ``(variant, x_f, y_f, g)``.

Computed at 200 segments with a fixed step and cross-checked between
collocation and single shooting. Regenerate with
``tools/generate_brachistochrone_references.py``.

The two transcriptions agree to 1.1e-10 s on the drag variant and to 0.02%
on the friction variant **at twenty segments**, but only to 13% at two
hundred, and the value stored is collocation's. That gap is worth stating
rather than averaging away. Friction here depends on the normal force,
which carries a centripetal term in the control's turning rate, and the
turning rate of a piecewise-linear control is piecewise constant: refining
the grid does not refine it, it chops it finer. Collocation is stable
across the refinement (0.9555 at twenty segments, 0.9557 at two hundred)
because the rate it uses is the segment slope by construction; shooting
integrates a right-hand side with a jump at every node and degrades.

The friction reference is therefore the weakest number in this library, and
a formulation that wanted it tighter would need the path angle as a state
with its rate as the control, which is a different problem rather than a
finer grid of this one.
"""


def cycloid_time(
    x_final: float = TARGET[0],
    y_final: float = TARGET[1],
    gravity: float = GRAVITY,
) -> float:
    """Return the exact minimum descent time of the ideal variant.

    Parameters
    ----------
    x_final
        The horizontal coordinate of the target, in m.
    y_final
        The depth of the target, in m.
    gravity
        The gravitational acceleration, in m/s**2.

    Returns
    -------
    float
        The descent time along the cycloid, in s.
    """
    ratio = x_final / y_final

    def aspect(theta: float) -> float:
        """Return the aspect-ratio residual at a cycloid angle."""
        return (theta - math.sin(theta)) / (1.0 - math.cos(theta)) - ratio

    # The bracket stays clear of the endpoints, where 1 - cos(theta)
    # underflows to exactly zero in double precision.
    theta_final = brentq(aspect, 1e-6, 2.0 * math.pi - 1e-6)
    radius = y_final / (1.0 - math.cos(theta_final))
    return theta_final * math.sqrt(radius / gravity)


def reference_time(
    variant: str = "ideal",
    x_final: float = TARGET[0],
    y_final: float = TARGET[1],
    gravity: float = GRAVITY,
) -> float:
    """Return the reference descent time of a variant.

    Parameters
    ----------
    variant
        The variant name.
    x_final
        The horizontal coordinate of the target, in m.
    y_final
        The depth of the target, in m.
    gravity
        The gravitational acceleration, in m/s**2.

    Returns
    -------
    float
        The reference descent time, in s: exact for the ideal variant, and
        the stored high-accuracy value otherwise.

    Raises
    ------
    KeyError
        If no stored reference covers the requested configuration.
    """
    if variant == "ideal":
        return cycloid_time(x_final, y_final, gravity)
    key = (variant, x_final, y_final, gravity)
    if key not in STORED_REFERENCES:
        raise KeyError(
            f"No stored reference for {key}; regenerate it with"
            " tools/generate_brachistochrone_references.py."
        )
    return STORED_REFERENCES[key]
