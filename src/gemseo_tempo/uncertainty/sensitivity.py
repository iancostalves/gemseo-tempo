"""Which uncertainties matter, screened first and then measured.

Two analyses, in the order they are worth doing.

:func:`screen` is a Morris one-at-a-time screening. It is cheap, it gives a
ranking rather than a decomposition, and its job is to find the variables not
worth spending a Sobol budget on. A screening that says a variable does
nothing is the cheapest result in uncertainty quantification.

:func:`sobol_indices` is the decomposition proper, and it is where this
library has something to offer. The Sobol design is generated by OpenTURNS,
evaluated **in one vectorized call** through
:func:`~gemseo_tempo.uncertainty.batch.batch_evaluator`, and reduced by the
Saltelli estimator. A design of experiments would run the same points one at a
time, because that is all it can do with a discipline it cannot see inside.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from dataclasses import field
from typing import TYPE_CHECKING

import numpy
import openturns

from gemseo_tempo.uncertainty.batch import batch_evaluator
from gemseo_tempo.uncertainty.spaces import make_parameter_space

if TYPE_CHECKING:
    from collections.abc import Sequence


@dataclass
class Screening:
    """What a Morris screening says about one quantity."""

    names: tuple[str, ...]
    """The uncertain variables, in the order the effects are given."""

    mean_effect: tuple[float, ...]
    """The mean absolute elementary effect of each, which is the ranking."""

    effect_spread: tuple[float, ...]
    """The spread of each, which is large when a variable interacts."""

    n_evaluations: int
    """How many evaluations the screening cost."""

    @property
    def ranking(self) -> list[str]:
        """Return the variables from most to least influential.

        Returns
        -------
        list
            The names, ordered by mean absolute effect.
        """
        order = numpy.argsort(self.mean_effect)[::-1]
        return [self.names[index] for index in order]

    def negligible(self, threshold: float = 0.05) -> list[str]:
        """Return the variables not worth a Sobol budget.

        Parameters
        ----------
        threshold
            The share of the largest mean effect below which a variable is
            called negligible.

        Returns
        -------
        list
            The names.
        """
        largest = max(self.mean_effect)
        if largest <= 0.0:
            return list(self.names)
        return [
            name
            for name, effect in zip(self.names, self.mean_effect, strict=True)
            if effect / largest < threshold
        ]


@dataclass
class SobolResult:
    """First-order and total Sobol indices of one quantity."""

    names: tuple[str, ...]
    """The uncertain variables."""

    first_order: tuple[float, ...]
    """The share of variance each variable explains on its own."""

    total: tuple[float, ...]
    """The share it explains alone and through every interaction."""

    n_evaluations: int
    """How many evaluations the design cost."""

    seconds: float
    """How long they took, evaluated all at once."""

    extra: dict = field(default_factory=dict)
    """Anything the caller wants carried alongside."""

    @property
    def interaction(self) -> tuple[float, ...]:
        """Return how much of each variable's effect is interaction.

        Returns
        -------
        tuple
            The total index minus the first-order one, per variable. A
            value near zero means the variable acts alone.
        """
        return tuple(
            total - first
            for total, first in zip(self.total, self.first_order, strict=True)
        )


def _distribution(registry, names: Sequence[str]) -> openturns.Distribution:
    """Return the joint distribution of the named variables.

    Parameters
    ----------
    registry
        The variable metadata.
    names
        The uncertain variable names.

    Returns
    -------
    openturns.Distribution
        The joint distribution, with independent margins.
    """
    space = make_parameter_space(registry, names)
    margins = [space.distributions[name].distribution for name in names]
    return openturns.JointDistribution(margins)


def screen(
    scenario,
    registry,
    names: Sequence[str],
    quantity: str,
    n_trajectories: int = 20,
    levels: int = 8,
) -> Screening:
    """Rank the uncertain variables by a Morris screening.

    Parameters
    ----------
    scenario
        The dynamic scenario.
    registry
        The variable metadata carrying the distributions.
    names
        The uncertain variable names.
    quantity
        The output to screen.
    n_trajectories
        The number of one-at-a-time trajectories.
    levels
        The number of levels of the Morris grid.

    Returns
    -------
    Screening
        The mean effect and spread of each variable.
    """
    distribution = _distribution(registry, names)
    dimension = len(names)
    lower = numpy.array(
        [
            distribution.getMarginal(index).computeQuantile(0.01)[0]
            for index in range(dimension)
        ]
    )
    upper = numpy.array(
        [
            distribution.getMarginal(index).computeQuantile(0.99)[0]
            for index in range(dimension)
        ]
    )
    step = (upper - lower) / (levels - 1)

    generator = numpy.random.default_rng(0)
    points = []
    for _ in range(n_trajectories):
        base = lower + generator.integers(0, levels - 1, dimension) * step
        points.append(base.copy())
        walk = base.copy()
        for index in generator.permutation(dimension):
            walk = walk.copy()
            walk[index] += step[index]
            points.append(walk.copy())
    sample = numpy.asarray(points)

    evaluate = batch_evaluator(scenario, names, [quantity])
    values = numpy.asarray(evaluate(sample)).ravel()

    per_trajectory = dimension + 1
    effects = [[] for _ in range(dimension)]
    for trajectory in range(n_trajectories):
        start = trajectory * per_trajectory
        block = sample[start : start + per_trajectory]
        block_values = values[start : start + per_trajectory]
        for position in range(dimension):
            moved = numpy.argmax(numpy.abs(block[position + 1] - block[position]) > 0.0)
            change = block[position + 1, moved] - block[position, moved]
            effects[moved].append(
                (block_values[position + 1] - block_values[position]) / change
            )

    return Screening(
        names=tuple(names),
        mean_effect=tuple(
            float(numpy.mean(numpy.abs(one))) if one else 0.0 for one in effects
        ),
        effect_spread=tuple(float(numpy.std(one)) if one else 0.0 for one in effects),
        n_evaluations=int(sample.shape[0]),
    )


def sobol_indices(
    scenario,
    registry,
    names: Sequence[str],
    quantity: str,
    n_samples: int = 512,
    seed: int = 0,
) -> SobolResult:
    """Decompose the variance of a quantity, evaluating the design at once.

    Parameters
    ----------
    scenario
        The dynamic scenario.
    registry
        The variable metadata carrying the distributions.
    names
        The uncertain variable names.
    quantity
        The output to decompose.
    n_samples
        The base size; the design costs ``n_samples * (len(names) + 2)``.
    seed
        The sampling seed.

    Returns
    -------
    SobolResult
        The first-order and total indices, and what they cost.
    """
    openturns.RandomGenerator.SetSeed(seed)
    distribution = _distribution(registry, names)
    experiment = openturns.SobolIndicesExperiment(distribution, n_samples)
    design = numpy.asarray(experiment.generate())

    evaluate = batch_evaluator(scenario, names, [quantity])
    evaluate(design).block_until_ready()
    started = time.perf_counter()
    values = numpy.asarray(evaluate(design).block_until_ready())
    seconds = time.perf_counter() - started

    algorithm = openturns.SaltelliSensitivityAlgorithm(
        openturns.Sample(design),
        openturns.Sample(values.reshape(-1, 1)),
        n_samples,
    )
    return SobolResult(
        names=tuple(names),
        first_order=tuple(float(v) for v in algorithm.getFirstOrderIndices()),
        total=tuple(float(v) for v in algorithm.getTotalOrderIndices()),
        n_evaluations=int(design.shape[0]),
        seconds=seconds,
    )


def format_indices(result: SobolResult) -> str:
    """Render Sobol indices as a table.

    Parameters
    ----------
    result
        The indices.

    Returns
    -------
    str
        One row per variable, first-order, total and interaction.
    """
    lines = [
        "| variable | first order | total | interaction |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend(
        f"| `{name}` | {first:.3f} | {total:.3f} | {gap:+.3f} |"
        for name, first, total, gap in zip(
            result.names,
            result.first_order,
            result.total,
            result.interaction,
            strict=True,
        )
    )
    return "\n".join(lines)


